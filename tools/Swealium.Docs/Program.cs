using System.Reflection;
using System.Globalization;
using System.Text;
using Swealium;

var directory = new DirectoryInfo(Environment.CurrentDirectory);
while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "Swealium.slnx"))) directory = directory.Parent;
if (directory is null) throw new InvalidOperationException("Run from the repository root or a child directory.");
string target = Path.Combine(directory.FullName, "docs", "api", "reference.md");
var nullable = new NullabilityInfoContext();
var types = typeof(SwealiumWindow).Assembly.GetExportedTypes().OrderBy(t => t.FullName, StringComparer.Ordinal).ToArray();
var text = new StringBuilder();
text.AppendLine("# Complete public API signatures").AppendLine();
text.AppendLine("Generated from the built Swealium assembly. Do not edit this file by hand. Regenerate with `dotnet run --project tools/Swealium.Docs -c Release`; CI checks for drift with `--check`.").AppendLine();
text.AppendLine("This inventory lists every exported type and its declared public/protected constructors, properties, events, fields, methods, overloads, and enum values. Inherited members are documented on the base type; collection operations are covered in [Widgets](widgets.md#widgetcollection). Record-generated equality, deconstruction, operators, and formatting members are included; the compiler-only clone method is omitted. Lifecycle, defaults, exceptions, and usage belong to the linked contract pages.").AppendLine();
text.AppendLine($"**{types.Length} exported types.**").AppendLine();
foreach (Type type in types)
    text.AppendLine($"- [{type.FullName}](#{Anchor(type)})");
text.AppendLine();
int memberCount = 0;
foreach (Type type in types)
{
    text.AppendLine($"<a id=\"{Anchor(type)}\"></a>").AppendLine();
    text.AppendLine($"## {type.FullName}").AppendLine();
    string contract = type.Namespace switch
    {
        "Swealium.Graphics" => "graphics.md",
        "Swealium.UI" => "widgets.md",
        "Swealium.Input" => "input.md",
        _ when type.Name.StartsWith("MessageBox", StringComparison.Ordinal) || type == typeof(DialogResult) => "dialogs.md",
        _ => "windowing.md"
    };
    text.AppendLine($"Behavior, defaults, and examples: [{contract[..^3]}]({contract}).").AppendLine();
    text.AppendLine("```csharp");
    bool recordClass = !type.IsValueType && type.GetMethod("<Clone>$") is not null;
    string kind = type.IsEnum ? "enum" : type.IsValueType ? "readonly record struct" :
        type.IsAbstract && type.IsSealed ? "static class" : (type.IsAbstract ? "abstract class" : type.IsSealed ? recordClass ? "sealed record" : "sealed class" : "class");
    var bases = new List<string>();
    if (type.BaseType is { } parent && parent != typeof(object) && !type.IsValueType) bases.Add(Name(parent));
    if (!type.IsEnum) bases.AddRange(type.GetInterfaces().Except(type.BaseType?.GetInterfaces() ?? []).OrderBy(t => t.FullName, StringComparer.Ordinal).Select(t => Name(t)));
    string baseType = bases.Count == 0 ? "" : " : " + string.Join(", ", bases);
    if (type.IsDefined(typeof(FlagsAttribute), false)) text.AppendLine("[Flags]");
    text.AppendLine($"public {kind} {type.FullName}{baseType}");
    if (type.IsEnum)
    {
        text.AppendLine("{");
        foreach (var field in type.GetFields(BindingFlags.Public | BindingFlags.Static))
        {
            text.AppendLine($"    {field.Name} = {Convert.ToInt64(field.GetRawConstantValue(), CultureInfo.InvariantCulture)},");
            memberCount++;
        }
        text.AppendLine("}").AppendLine("```").AppendLine();
        continue;
    }
    text.AppendLine("{");
    const BindingFlags flags = BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;
    var signatures = new List<string>();
    foreach (var ctor in type.GetConstructors(flags).Where(Visible))
        signatures.Add($"{Access(ctor)} {type.Name}({string.Join(", ", ctor.GetParameters().Select(Parameter))});");
    foreach (var property in type.GetProperties(flags).OrderBy(p => p.Name, StringComparer.Ordinal))
    {
        var accessors = property.GetAccessors(true).Where(Visible).ToArray();
        if (accessors.Length == 0) continue;
        string access = accessors.Any(a => a.IsPublic) ? "public" : "protected";
        string modifiers = accessors[0].IsStatic ? "static " : "";
        string propertyName = property.GetIndexParameters().Length > 0
            ? "this[" + string.Join(", ", property.GetIndexParameters().Select(Parameter)) + "]" : property.Name;
        var parts = new List<string>();
        if (property.GetMethod is { } get && Visible(get)) parts.Add((get.IsPublic || access == "protected" ? "" : "protected ") + "get;");
        if (property.SetMethod is { } set && Visible(set))
            parts.Add((set.IsPublic || access == "protected" ? "" : "protected ") +
                (set.ReturnParameter.GetRequiredCustomModifiers().Any(t => t.Name == "IsExternalInit") ? "init;" : "set;"));
        signatures.Add($"{access} {modifiers}{Name(property.PropertyType, nullable.Create(property))} {propertyName} {{ {string.Join(" ", parts)} }}");
    }
    foreach (var evt in type.GetEvents(flags).Where(e => e.AddMethod is { } a && Visible(a)).OrderBy(e => e.Name, StringComparer.Ordinal))
        signatures.Add($"{Access(evt.AddMethod!)} event {Name(evt.EventHandlerType!, nullable.Create(evt))} {evt.Name};");
    foreach (var field in type.GetFields(flags).Where(f => f.IsPublic || f.IsFamily || f.IsFamilyOrAssembly).OrderBy(f => f.Name, StringComparer.Ordinal))
        signatures.Add($"{(field.IsPublic ? "public" : "protected")} {(field.IsStatic ? "static " : "")}{(field.IsInitOnly ? "readonly " : "")}{Name(field.FieldType)} {field.Name};");
    foreach (var method in type.GetMethods(flags).Where(m => Visible(m) && (!m.IsSpecialName || m.Name.StartsWith("op_", StringComparison.Ordinal)) && !m.Name.Contains('<'))
        .OrderBy(m => m.Name, StringComparer.Ordinal).ThenBy(m => string.Join(",", m.GetParameters().Select(p => p.ParameterType.FullName)), StringComparer.Ordinal))
    {
        string modifiers = method.IsStatic ? "static " : method.IsAbstract ? "abstract " :
            method.GetBaseDefinition() != method ? "override " : method.IsVirtual && !method.IsFinal ? "virtual " : "";
        string name = method.Name switch { "op_Equality" => "operator ==", "op_Inequality" => "operator !=", _ => method.Name };
        signatures.Add($"{Access(method)} {modifiers}{Name(method.ReturnType, nullable.Create(method.ReturnParameter))} {name}({string.Join(", ", method.GetParameters().Select(Parameter))});");
    }
    foreach (string signature in signatures) text.AppendLine("    " + signature);
    memberCount += signatures.Count;
    text.AppendLine("}").AppendLine("```").AppendLine();
}
string expected = text.ToString().Replace("\r\n", "\n");
if (args.Contains("--check"))
{
    if (!File.Exists(target) || File.ReadAllText(target).Replace("\r\n", "\n") != expected)
        throw new InvalidOperationException("API reference is stale. Run the documentation generator.");
}
else
{
    Directory.CreateDirectory(Path.GetDirectoryName(target)!);
    File.WriteAllText(target, expected, new UTF8Encoding(false));
}
Console.WriteLine($"API reference {(args.Contains("--check") ? "verified" : "generated")}: {types.Length} types, {memberCount} declared members.");

static bool Visible(MethodBase method) => method.IsPublic || method.IsFamily || method.IsFamilyOrAssembly;
static string Access(MethodBase method) => method.IsPublic ? "public" : "protected";
static string Anchor(Type type) => type.FullName!.Replace('.', '-').ToLowerInvariant();
string Parameter(ParameterInfo parameter)
{
    Type type = parameter.ParameterType;
    string prefix = type.IsByRef ? parameter.IsOut ? "out " : parameter.IsIn ? "in " : "ref " : "";
    if (type.IsByRef) type = type.GetElementType()!;
    return prefix + Name(type, nullable.Create(parameter)) + " " + parameter.Name +
        (parameter.HasDefaultValue ? " = " + Default(parameter.DefaultValue, type) : "");
}
static string Default(object? value, Type type)
{
    if (value is null) return type.IsValueType && Nullable.GetUnderlyingType(type) is null ? "default" : "null";
    if (type.IsEnum) return Name(type) + "." + Enum.GetName(type, value);
    return value switch
    {
        string s => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"",
        bool b => b ? "true" : "false",
        float f => f.ToString(CultureInfo.InvariantCulture) + "f",
        _ => Convert.ToString(value, CultureInfo.InvariantCulture) ?? "default"
    };
}
static string Name(Type type, NullabilityInfo? info = null)
{
    if (type.IsByRef) type = type.GetElementType()!;
    string name = type == typeof(void) ? "void" : type == typeof(bool) ? "bool" : type == typeof(byte) ? "byte" :
        type == typeof(int) ? "int" : type == typeof(uint) ? "uint" : type == typeof(float) ? "float" :
        type == typeof(string) ? "string" : type == typeof(object) ? "object" : type == typeof(IntPtr) ? "nint" :
        type == typeof(UIntPtr) ? "nuint" : type == typeof(long) ? "long" : type == typeof(ulong) ? "ulong" : type.Name;
    if (Nullable.GetUnderlyingType(type) is { } underlying) return Name(underlying, info?.GenericTypeArguments.FirstOrDefault()) + "?";
    if (type.IsArray) return Name(type.GetElementType()!, info?.ElementType) + "[]";
    if (type.IsGenericType)
    {
        name = (type.Namespace?.StartsWith("Swealium", StringComparison.Ordinal) == true ? type.Namespace + "." : "") + type.Name.Split('`')[0];
        var arguments = type.GetGenericArguments();
        name += "<" + string.Join(", ", arguments.Select((t, i) => Name(t, info?.GenericTypeArguments.ElementAtOrDefault(i)))) + ">";
    }
    else if (type.Namespace?.StartsWith("Swealium", StringComparison.Ordinal) == true) name = type.FullName!;
    if (!type.IsValueType && info?.ReadState == NullabilityState.Nullable) name += "?";
    return name;
}

